-- One-time Snowflake setup for TailSignal. Run in a Snowsight worksheet as ACCOUNTADMIN.
-- Reuses the MedicareFWA service user (FWA_SVC, key-pair auth) and warehouse (FWA_WH, with its
-- resource monitor), so no new key is needed.

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS TAILSIGNAL;
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.RAW;           -- partner files as loaded
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.REFERENCE;     -- dbt seeds (taxonomies)
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.STAGING;       -- dbt views, one per source file
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.INTERMEDIATE;  -- profiles, breed map, entity-resolution output
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.CORE;          -- dim_pet, fct_service_event, ...
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.PRODUCT;       -- k-anonymous data products
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.QA;
CREATE SCHEMA IF NOT EXISTS TAILSIGNAL.GOVERNANCE;    -- masking policies (dbt/macros/governance.sql)

CREATE ROLE IF NOT EXISTS TAILSIGNAL_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE FWA_WH TO ROLE TAILSIGNAL_ROLE;
GRANT USAGE ON DATABASE TAILSIGNAL TO ROLE TAILSIGNAL_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE TAILSIGNAL TO ROLE TAILSIGNAL_ROLE;
GRANT ROLE TAILSIGNAL_ROLE TO ROLE SYSADMIN;
GRANT ROLE TAILSIGNAL_ROLE TO USER FWA_SVC;

-- tasks: the incremental daycare load runs as a task graph owned by TAILSIGNAL_ROLE (src/tailsignal/sf.py)
GRANT EXECUTE TASK ON ACCOUNT TO ROLE TAILSIGNAL_ROLE;

-- analyst role: reads staging, intermediate, core and product, never RAW; owner fields arrive masked
CREATE ROLE IF NOT EXISTS TAILSIGNAL_ANALYST;
GRANT USAGE ON WAREHOUSE FWA_WH TO ROLE TAILSIGNAL_ANALYST;
GRANT USAGE ON DATABASE TAILSIGNAL TO ROLE TAILSIGNAL_ANALYST;
GRANT USAGE ON SCHEMA TAILSIGNAL.STAGING      TO ROLE TAILSIGNAL_ANALYST;
GRANT USAGE ON SCHEMA TAILSIGNAL.INTERMEDIATE TO ROLE TAILSIGNAL_ANALYST;
GRANT USAGE ON SCHEMA TAILSIGNAL.CORE         TO ROLE TAILSIGNAL_ANALYST;
GRANT USAGE ON SCHEMA TAILSIGNAL.PRODUCT      TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON ALL TABLES    IN SCHEMA TAILSIGNAL.INTERMEDIATE TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TAILSIGNAL.INTERMEDIATE TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON ALL TABLES    IN SCHEMA TAILSIGNAL.CORE         TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TAILSIGNAL.CORE         TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON ALL TABLES    IN SCHEMA TAILSIGNAL.PRODUCT      TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TAILSIGNAL.PRODUCT      TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON ALL VIEWS     IN SCHEMA TAILSIGNAL.STAGING      TO ROLE TAILSIGNAL_ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA TAILSIGNAL.STAGING      TO ROLE TAILSIGNAL_ANALYST;
GRANT ROLE TAILSIGNAL_ANALYST TO ROLE SYSADMIN;
GRANT ROLE TAILSIGNAL_ANALYST TO USER FWA_SVC;   -- lets `python -m tailsignal.sf masking-check` query as an analyst
